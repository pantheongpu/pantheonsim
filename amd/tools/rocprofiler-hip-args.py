#!/usr/bin/env python3
"""Writes amd/src/rocprofiler_hip_args.inc: what rocprofiler-sdk records of each
HIP call's arguments, so the simulator's records carry them the way the real
library's do (names, order, the layout of rocprofiler_hip_api_args_t, the kind
of each parameter, its typeid name).

  amd/tools/rocprofiler-hip-args.py <ROCm include dir> [out]

Needs a C++ compiler (g++ or clang++) and ROCm's headers: the layout (offsets,
sizes) and the kind of every parameter come from compiling a probe against
rocprofiler-sdk/hip/api_args.h, not from reading its types, so the table is
exactly what that header's union is. Run it when a new ROCm adds HIP calls, then
rocprofiler-hip-ids.py for their numbers.
"""
import os
import re
import subprocess
import sys
import tempfile

HEADER = '''// What rocprofiler-sdk records of each HIP call's arguments, from its
// hip/api_args.h (MIT licence, Copyright (c) 2023-2025 Advanced Micro Devices,
// Inc.; the notice is in vgpu/rocprofiler_abi.hpp). Generated by
// amd/tools/rocprofiler-hip-args.py; do not edit.
//
// HIP_ARGS(call, argument count, then per argument: name, kind, offset in
// rocprofiler_hip_api_args_t, size, typeid name)
'''

PROBE = r'''
#include <rocprofiler-sdk/hip/api_args.h>
#include <cstddef>
#include <cstdio>
#include <type_traits>
#include <typeinfo>

using U = rocprofiler_hip_api_args_t;

template <class T, class = void> struct complete : std::false_type {};
template <class T> struct complete<T, std::void_t<decltype(sizeof(T))>> : std::true_type {};

// The kinds, as in rocprofiler_sdk.cpp's ArgKind.
enum { SIGNED = 0, UNSIGNED, FLOAT, MEMCPY_KIND, ENUM, PTR_VOID, PTR_CHAR, PTR_OPAQUE, PTR_PTR, PTR_DATA, FUNC_PTR, DIM3, OTHER, EXTENT, PITCHED_PTR, MEM_LOCATION };

template <class T> int kind() {
  using R = std::remove_cv_t<T>;
  if constexpr (std::is_same_v<R, hipMemcpyKind>) return MEMCPY_KIND;
  else if constexpr (std::is_enum_v<R>) return ENUM;
  else if constexpr (std::is_same_v<R, bool>) return OTHER;
  else if constexpr (std::is_integral_v<R>) return std::is_signed_v<R> ? SIGNED : UNSIGNED;
  else if constexpr (std::is_floating_point_v<R>) return FLOAT;
  else if constexpr (std::is_same_v<R, rocprofiler_dim3_t>) return DIM3;
  else if constexpr (std::is_same_v<R, hipExtent>) return EXTENT;
  else if constexpr (std::is_same_v<R, hipPitchedPtr>) return PITCHED_PTR;
  else if constexpr (std::is_same_v<R, hipMemLocation>) return MEM_LOCATION;
  else if constexpr (std::is_function_v<std::remove_pointer_t<R>>) return FUNC_PTR;
  else if constexpr (std::is_pointer_v<R>) {
    using P = std::remove_cv_t<std::remove_pointer_t<R>>;
    if constexpr (std::is_void_v<P>) return PTR_VOID;
    else if constexpr (std::is_same_v<P, char>) return PTR_CHAR;
    else if constexpr (std::is_pointer_v<P>) return PTR_PTR;
    else if constexpr (!complete<P>::value) return PTR_OPAQUE;
    else return PTR_DATA;
  } else return OTHER;
}

template <class T> void row(const char* field, size_t off) {
  std::printf("%s %d %zu %zu %s\n", field, kind<T>(), off, sizeof(T), typeid(T).name());
}
#define F(op, field) row<decltype(U::op.field)>(#field, offsetof(U, op.field))
int main() {
'''


def struct_members(preprocessed):
    """(call, [field, ...]) for each member struct of the union, in the header's order."""
    start = preprocessed.index('typedef union rocprofiler_hip_api_args_t')
    body = preprocessed[start:]
    body = body[:body.index('} rocprofiler_hip_api_args_t;')]
    out = []
    for m in re.finditer(r'struct\s*\{(.*?)\}\s*(\w+);', body, re.S):
        fields = []
        for decl in m.group(1).split(';'):
            decl = decl.strip()
            if not decl or 'rocprofiler_hip_api_no_args' in decl:   # a call with no arguments
                continue
            f = re.search(r'(\w+)\s*(?:\[[^\]]*\])?$', decl)
            fields.append(f.group(1))
        out.append((m.group(2), fields))
    return out


def main():
    inc = sys.argv[1]
    dest = sys.argv[2] if len(sys.argv) > 2 else 'amd/src/rocprofiler_hip_args.inc'
    cxx = os.environ.get('CXX', 'g++')
    flags = [f'-I{inc}', '-D__HIP_PLATFORM_AMD__', '-std=c++17', '-w']
    with tempfile.TemporaryDirectory() as tmp:
        stub = os.path.join(tmp, 'stub.cpp')
        with open(stub, 'w') as f:
            f.write('#include <rocprofiler-sdk/hip/api_args.h>\n')
        pre = subprocess.run([cxx, '-E', '-P'] + flags + [stub], check=True, capture_output=True, text=True).stdout
        members = struct_members(pre)
        probe = os.path.join(tmp, 'probe.cpp')
        with open(probe, 'w') as f:
            f.write(PROBE)
            for call, fields in members:
                f.write(f'  std::printf("@ %s %zu\\n", "{call}", (size_t){len(fields)});\n')
                for field in fields:
                    f.write(f'  F({call}, {field});\n')
            f.write('}\n')
        exe = os.path.join(tmp, 'probe')
        subprocess.run([cxx] + flags + [probe, '-o', exe], check=True)
        text = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    lines = [HEADER]
    cur = None
    for line in text.splitlines():
        if line.startswith('@ '):
            if cur:
                lines.append(cur + ')')
            _, call, count = line.split()
            cur = f'HIP_ARGS({call}, {count}'
        else:
            name, kind, off, size, tid = line.split()
            cur += f',\n    {{"{name}", {kind}, {off}, {size}, "{tid}"}}'
    lines.append(cur + ')')
    with open(dest, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
