#!/usr/bin/env python3
"""Generate amd/src/rocprofiler_rdna_agents.inc: the fields of a Radeon card's rocprofiler agent that its
profile does not carry (shader engines and arrays, SDMA engines, queues, clocks, memory banks, caches, io
links, firmware), as rocprofv3 printed them on the card.

    rocprof-agent-inc.py <card results.json> <kfd-topology.txt> [<card results.json> <kfd-topology.txt> ...]

The results.json is rocprofv3's (--kernel-trace --output-format json) on the card; the topology file is
amd/registers/measurements/<card>/kfd-topology.txt (the capability word, which rocprofv3 prints as bits). Only
what is the card's own is taken; where the card sits in a machine (node, gpu_id, location, render minor, uuid)
is not a fact about the card and stays what the simulated machine says.
"""
import json
import re
import sys

CACHE = {"Data": 1, "Instruction": 2, "CPU": 4, "HSACU": 8}
LINK = {"Override": 1, "NonCoherent": 2, "NoAtomics32bit": 4, "NoAtomics64bit": 8, "NoPeerToPeerDMA": 16}
BANK = {"HotPluggable": 1, "NonVolatile": 2}


def bits(d, table):
    return sum(table[k] for k, v in d.items() if v)


def capability(path, name):
    text = open(path).read()
    m = re.search(r"##### \d+ name=%s .*?\ncapability (\d+)" % name, text, re.S)
    return int(m.group(1))


def card(results, topo):
    tool = json.load(open(results))["rocprofiler-sdk-tool"][0]
    a = [x for x in tool["agents"] if x["type"] == 2 and x["runtime_visibility"]["hip"] and x["model_name"]][0]
    cap = capability(topo, a["model_name"])
    scalars = ["simd_id_base", "num_gws", "num_xcc", "array_count", "num_shader_banks", "simd_arrays_per_engine",
               "cu_per_simd_array", "max_slots_scratch_cu", "num_sdma_engines", "num_sdma_xgmi_engines",
               "num_sdma_queues_per_engine", "num_cp_queues", "max_engine_clk_ccompute", "max_engine_clk_fcompute",
               "cu_per_engine", "family_id", "grid_max_size", "local_mem_size"]
    out = ["  {%d, \"%s\"," % (a["device_id"], a["model_name"])]
    out.append("   {%s}," % ", ".join(str(a[k]) for k in scalars))
    out.append("   %d, %d, %d, %d, %d, %d," % (a["sdma_fw_version"]["uCodeSDMA"], a["fw_version"]["uCode"], cap,
                                               a["grid_max_dim"]["x"], a["grid_max_dim"]["y"], a["grid_max_dim"]["z"]))
    out.append("   %d, %d," % (a["runtime_visibility"]["rccl"], a["runtime_visibility"]["rocdecode"]))
    out.append("   {%s}," % ", ".join("{%d, %d, %d, %d, %d}" % (b["heap_type"], bits(b["flags"], BANK), b["width"],
                                                                 b["mem_clk_max"], b["size_in_bytes"])
                                       for b in a["mem_banks"]))
    out.append("   {%s}," % ",\n    ".join(
        "{%d, %d, %d, %d, %d, %d, %d}" % (c["processor_id_low"], c["size"], c["level"], c["cache_line_size"],
                                         c["cache_lines_per_tag"], c["association"], bits(c["type"], CACHE))
        for c in a["caches"]))
    # An io link runs from the card's node to the CPU's (node 0): the card's own node is the machine's.
    out.append("   {%s}}," % ", ".join(
        "{%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d}" % (
            l["type"], l["version_major"], l["version_minor"], l["weight"], l["min_latency"], l["max_latency"],
            l["min_bandwidth"], l["max_bandwidth"], l["recommended_transfer_size"], bits(l["flags"], LINK), l["node_to"])
        for l in a["io_links"]))
    return "\n".join(out)


def main():
    if len(sys.argv) < 3 or len(sys.argv) % 2 == 0:
        sys.exit(__doc__)
    print("// Generated by amd/tools/rocprof-agent-inc.py from rocprofv3 on the cards; do not edit.")
    for i in range(1, len(sys.argv), 2):
        print(card(sys.argv[i], sys.argv[i + 1]))


if __name__ == "__main__":
    main()
