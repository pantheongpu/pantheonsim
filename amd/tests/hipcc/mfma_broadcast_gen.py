#!/usr/bin/env python3
"""Writes mfma_broadcast_golden.h: where AMD's Matrix Instruction Calculator says each element of A, B and D sits (register, lane, bit
position) for a family of MFMA shapes, and what its --cbsz and --abid options do to A.

  git clone https://github.com/ROCm/amd_matrix_instruction_calculator
  mfma_broadcast_gen.py <path to matrix_calculator.py> > mfma_broadcast_golden.h

Needs Python 3 and the calculator's own requirement (tabulate). The tables come from the calculator and nothing else: not from the ISA guides'
prose and not from the simulator. The calculator's CDNA2 and CDNA3 tables are checked equal for the shapes both have (the header is one
table, used for gfx90a, gfx942 and gfx950).
"""
import re
import subprocess
import sys

CALC = sys.argv[1]

# (key, kind, CDNA3 name, CDNA2 name, compiler builtin); the 8-bit integer shapes lay A out the same way and are left out to keep the table small
FAMILIES = [
    ("f32_32x32x1_2b", "f32", "v_mfma_f32_32x32x1_2b_f32", "v_mfma_f32_32x32x1f32", "mfma_f32_32x32x1f32"),
    ("f32_16x16x1_4b", "f32", "v_mfma_f32_16x16x1_4b_f32", "v_mfma_f32_16x16x1f32", "mfma_f32_16x16x1f32"),
    ("f32_4x4x1_16b", "f32", "v_mfma_f32_4x4x1_16b_f32", "v_mfma_f32_4x4x1f32", "mfma_f32_4x4x1f32"),
    ("f16_32x32x4_2b", "f16", "v_mfma_f32_32x32x4_2b_f16", "v_mfma_f32_32x32x4f16", "mfma_f32_32x32x4f16"),
    ("f16_16x16x4_4b", "f16", "v_mfma_f32_16x16x4_4b_f16", "v_mfma_f32_16x16x4f16", "mfma_f32_16x16x4f16"),
    ("f16_4x4x4_16b", "f16", "v_mfma_f32_4x4x4_16b_f16", "v_mfma_f32_4x4x4f16", "mfma_f32_4x4x4f16"),
]

CELL = re.compile(r"v(\d+)\{(\d+)\}(?:\.\[(\d+):(\d+)\])?")


def calc(arch, inst, *args):
    out = subprocess.run([sys.executable, CALC, "-a", arch, "-i", inst] + list(args), capture_output=True, text=True, check=True)
    return out.stdout


def detail(arch, inst):
    t = calc(arch, inst, "-d")
    g = lambda k: int(re.search(r"\b%s: (\d+)" % k, t).group(1))
    return g("M"), g("N"), g("K"), g("blocks")


def layout(arch, inst, matrix, *args):
    """{(block, row, col): (reg, lane, low bit)} from the calculator's CSV register layout."""
    text = calc(arch, inst, "-R", "-" + matrix, "--csv", *args)
    out = {}
    blocks = None
    cols = None
    for line in text.splitlines():
        if line.startswith(("Architecture", "Instruction")) or not line.strip():
            continue
        if line.startswith("Block"):
            blocks = [int(x) for x in re.findall(r"\d+", line)]
            continue
        parts = line.split(",")
        if parts[0].endswith("]") and "[" in parts[0]:   # "A[M][K],0,1,2,3": the column header
            cols = parts[1:]
            continue
        row = int(parts[0])
        for col, cell in zip(cols, parts[1:]):
            m = CELL.fullmatch(cell.strip())
            assert m, (inst, matrix, cell)
            reg, lane = int(m.group(1)), int(m.group(2))
            lo = int(m.group(4)) if m.group(4) is not None else 0
            for b in blocks:
                out[(b, row, int(col))] = (reg, lane, lo)
    return out


def configs(blocks):
    """The legal (CBSZ, ABID) pairs, thinned for the wide ones: every pair up to CBSZ 2, then the first, the last and a middle ABID."""
    top = {1: 0, 2: 1, 4: 2, 8: 3, 16: 4}[blocks]
    for cbsz in range(top + 1):
        n = 1 << cbsz
        abids = list(range(n)) if cbsz <= 2 else sorted({0, 1, n // 2 + 1, n - 1})
        for a in abids:
            yield cbsz, a


def pack(loc, kind):
    reg, lane, lo = loc
    sub = lo // {"f32": 32, "f16": 16}[kind]
    assert reg < 4 and sub < 4 and lane < 64
    return lane | reg << 6 | sub << 8


def pack_d(loc):
    reg, lane, lo = loc
    assert reg < 32 and lane < 64 and lo == 0
    return lane | reg << 6


def main():
    print("// Generated by mfma_broadcast_gen.py from AMD's Matrix Instruction Calculator (github.com/ROCm/amd_matrix_instruction_calculator):")
    print("// do not edit. Each entry is where the calculator puts one matrix element: lane | register << 6 | sub-element << 8 (D: lane | register << 6), in the order")
    print("// block, row, column (A: row = M, column = K; B: row = K, column = N; D: row = M, column = N).")
    print("#pragma once")
    print("#include <cstdint>")
    print("struct Family { const char* key; int kind; int M, N, K, blocks; int a_regs, b_regs, d_regs; const uint16_t* b; const uint16_t* d; };")
    fam_lines = []
    cfg_lines = []
    for fi, (key, kind, name3, name2, builtin) in enumerate(FAMILIES):
        M, N, K, blocks = detail("cdna3", name3)
        assert detail("cdna2", name2) == (M, N, K, blocks)
        bmap = layout("cdna3", name3, "B")
        dmap = layout("cdna3", name3, "D")
        assert bmap == layout("cdna2", name2, "B") and dmap == layout("cdna2", name2, "D"), key
        a_all = {}
        for cbsz, abid in configs(blocks):
            extra = ["--cbsz", str(cbsz), "--abid", str(abid)] if cbsz else []
            a3 = layout("cdna3", name3, "A", *extra)
            a2 = layout("cdna2", name2, "A", *extra)
            assert a3 == a2, (key, cbsz, abid)
            a_all[(cbsz, abid)] = a3
        regs = lambda m: max(v[0] for v in m.values()) + 1
        a_regs, b_regs, d_regs = regs(a_all[(0, 0)]), regs(bmap), regs(dmap)
        for name, m in [("b", bmap), ("d", dmap)]:
            vals = [pack(m[(b, r, c)], kind) if name == "b" else pack_d(m[(b, r, c)]) for b in range(blocks)
                    for r in range(K if name == "b" else M) for c in range(N)]
            print("static const uint16_t %s_%s[] = {%s};" % (key, name, ",".join("0x%x" % v for v in vals)))
        for (cbsz, abid), m in a_all.items():
            vals = [pack(m[(b, r, c)], kind) for b in range(blocks) for r in range(M) for c in range(K)]
            print("static const uint16_t %s_a_%d_%d[] = {%s};" % (key, cbsz, abid, ",".join("0x%x" % v for v in vals)))
            cfg_lines.append("  X(%d, %d, %d, %s_a_%d_%d)" % (fi, cbsz, abid, key, cbsz, abid))
        fam_lines.append('  {"%s", %d, %d, %d, %d, %d, %d, %d, %d, %s_b, %s_d},' % (
            key, {"f32": 0, "f16": 1}[kind], M, N, K, blocks, a_regs, b_regs, d_regs, key, key))
    print("static const Family kFamilies[] = {\n%s\n};" % "\n".join(fam_lines))
    print("#define MFMA_CONFIGS(X) \\\n%s" % " \\\n".join(cfg_lines))


main()
