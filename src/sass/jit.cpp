void Unit::note(uint32_t region, uint32_t k) {
  Manager& mgr = manager();
  int s = state.load(std::memory_order_relaxed);
  if (s > static_cast<int>(State::Counting)) return;
  const uint64_t c = counts[region].fetch_add(k, std::memory_order_relaxed) + k;
  // (The section's total is worked out only when this region's count passes a multiple of check_mask + 1: one atomic add per run, not two.)
  if ((c & mgr.check_mask) >= k) return;
  uint64_t total = 0;
  for (size_t i = 0; i < regions.size(); ++i) total += counts[i].load(std::memory_order_relaxed);
  executed.store(total, std::memory_order_relaxed);
  total += credit.load(std::memory_order_relaxed);   // (what a wait on the plain loop ran, once it is over)
  if (s == static_cast<int>(State::Idle) && total >= mgr.lookup_after && (mutant("share_no_defer") || !sampling.load(std::memory_order_acquire))) {   // (the share rule decides first: a declined section asks nobody)
    int exp = static_cast<int>(State::Idle);
    if (state.compare_exchange_strong(exp, static_cast<int>(State::Looking))) mgr.submit(Job::Lookup, shared_from_this());   // (inline in synchronous mode)
    s = state.load(std::memory_order_acquire);
  }
  if (total < mgr.threshold || s != static_cast<int>(State::Counting)) return;
  int exp = static_cast<int>(State::Counting);
  if (state.compare_exchange_strong(exp, static_cast<int>(State::Queued))) mgr.submit(Job::Compile, shared_from_this());
}

void Unit::wait_note(uint64_t instr) {
  // (One section's remainder is dropped when the thread goes on to another: that only makes the first one's wait longer.)
  static thread_local const Unit* mine = nullptr;
  static thread_local uint64_t n = 0;
  if (mine != this) {
    mine = this;
    n = 0;
  }
  n += instr;
  if (n < wait_batch.load(std::memory_order_relaxed)) return;
  const uint64_t t = waited.fetch_add(n, std::memory_order_relaxed) + n;
  n = 0;
  if (t >= wait_for.load(std::memory_order_relaxed)) wait_over();
}

// The wait is over: what it ran counts towards the threshold, and the section is Counting again (the hook loop, the regions' counts) for the last stretch.
// (Round sp63: a wait before the lookup ends in Idle, the hook loop's counting up to the lookup; what it ran counts towards the lookup and the threshold.)
void Unit::wait_over() {
  const int then = wait_then.load(std::memory_order_relaxed);
  if (mutant(then == static_cast<int>(State::Idle) ? "prewait_stuck" : "wait_stuck")) return;
  int exp = static_cast<int>(State::Waiting);
  if (!state.compare_exchange_strong(exp, then, std::memory_order_acq_rel)) return;
  if (!mutant("wait_no_credit")) credit.fetch_add(wait_for.load(std::memory_order_relaxed), std::memory_order_relaxed);
  stats().wait_ends.fetch_add(1);
}

const ShareRule& share_rule() { return manager().share; }


uint64_t Unit::gen_work() const {
  uint64_t w = 0;
  for (size_t i = 0; i < regions.size(); ++i)
    if (regions[i].k) w += counts[i].load(std::memory_order_relaxed) * regions[i].gen / regions[i].k;
  return w;
}

void Unit::sample(uint64_t instr) {
  if (!sampling.load(std::memory_order_relaxed)) return;
  const ShareRule& r = manager().share;
  const uint64_t t = sampled.fetch_add(instr, std::memory_order_relaxed) + instr;
  if (t < r.sample_after) return;
  if (!sampling.exchange(false, std::memory_order_acq_rel)) return;   // (the thread that completes the sample decides, once)
  const uint64_t gw = gen_work();
  const bool ok = mutant("share_all_on") ? true : mutant("share_all_off") ? false : share_ok(gw, t, r);
  if (stats_on()) std::fprintf(stderr, "jit: share rule: a section sampled over %llu warp instructions, %llu per thousand of them computed by generated code (bar %u): %s\n",
                               (unsigned long long)t, (unsigned long long)(gw * 1000 / (t ? t : 1)), r.min_share_permille, ok ? "kept" : "declined");
  if (ok) {
    stats().accepted.fetch_add(1);
    // (Round sp63) The way to the lookup on the plain loop too: a kept section still far from the lookup waits for it as a section far from its threshold
    // does (State::Waiting), and is Idle again, in the hook loop, once all of its instructions make up the rest of VGPU_JIT_LOOKUP_AFTER. Until then a kept
    // section was counted region by region in the hook loop all the way to the lookup, or for its whole life when it never got there (round sp57: ADI,
    // asmooth, sortKV 6 to 8 % slower cold). The lookup comes up to 2.5 times earlier (all instructions count, not only those in regions).
    Manager& mgr = manager();
    if (mgr.profile != 0 && !mutant("prewait_never")) {
      uint64_t done = 0;
      for (size_t i = 0; i < regions.size(); ++i) done += counts[i].load(std::memory_order_relaxed);
      if (mgr.lookup_after > done && mgr.lookup_after - done >= kPrewaitMin) {
        const uint64_t n = mgr.lookup_after - done;
        wait_for.store(n, std::memory_order_relaxed);
        // (a thread brings its share to the count in batches of a 64th of the wait: sixteen threads end it at most a quarter late, and none passes the
        // count's cache line around on every call of the loop)
        wait_batch.store(n >= kWaitBatch && !mutant("wait_no_batch") ? n >> 6 : 1, std::memory_order_relaxed);
        waited.store(0, std::memory_order_relaxed);
        wait_then.store(static_cast<int>(mutant("prewait_to_counting") ? State::Counting : State::Idle), std::memory_order_relaxed);
        int exp = static_cast<int>(State::Idle);
        if (state.compare_exchange_strong(exp, static_cast<int>(State::Waiting), std::memory_order_acq_rel)) stats().prewaits.fetch_add(1);
      }
    }
    return;
  }
  stats().declined.fetch_add(1);
  for (int s = state.load(); s == static_cast<int>(State::Idle) || s == static_cast<int>(State::Counting);)
    if (state.compare_exchange_weak(s, static_cast<int>(State::Declined), std::memory_order_acq_rel)) break;
}

void drain() { manager().drain(); }

const char* exit_name(unsigned why) {
  static const char* const names[kExCount] = {"split-branch", "uniform-branch-taken", "uniform-branch-not-taken", "register-only-op", "turn-budget", "run-bound",
                                              "step-budget", "store-gate", "to-compiled-region", "bssy-nop", "bsync", "exit", "exit-no-lane-leaves", "call-ret", "bar-yield-warpsync",
                                              "branch-outside-regions", "straight-op-outside-regions", "handler-op", "interpreter-op"};
  return why < kExCount ? names[why] : "?";
}

void Manager::report() {
  const char* v = std::getenv("VGPU_JIT_STATS");
  if (!(v && *v && v[0] != '0')) return;
  std::FILE* out = stderr;
  if (const char* f = std::getenv("VGPU_JIT_STATS_FILE"); f && *f)
    if (std::FILE* g = std::fopen(f, "a")) out = g;
  Stats& s = stats();
  if (link_requested())
    std::fprintf(out, "jit: link in-diverged-warps: %llu\njit: link calls-with-a-split: %llu\njit: link sections-left-unlinked-by-the-loop-rule: %llu\n",
                 (unsigned long long)s.linked.load(), (unsigned long long)s.splits.load(), (unsigned long long)s.link_declined.load());
  // Why the region calls ended (one line a reason that occurred): all, of them in a diverged warp, of them at the entry with nothing run. These lines
  // come before the summary: what reads a statistics file takes its last "jit: " line for the summary (run_sass_jit.sh).
  for (unsigned w = 0; w < kExCount; ++w) {
    const uint64_t a = s.exits[w][0].load(), d = s.exits[w][1].load(), z = s.exits[w][2].load();
    if (a + d) std::fprintf(out, "jit: exit %s: %llu (diverged warp %llu, nothing run %llu)\n", exit_name(w), (unsigned long long)(a + d), (unsigned long long)d, (unsigned long long)z);
  }
  std::fprintf(out,
               "jit: %llu units (%llu regions), %llu ready, %llu cache hits, %llu compiles (%.1f ms), %llu failures, %llu damaged objects replaced; "
               "%llu region calls ran %llu warp instructions (%llu computed by generated code), %llu exceptions unwound through them; share rule: %llu declined, %llu accepted; "
               "%llu branches and register-only ops continued inside generated code\n",
               (unsigned long long)s.units.load(), (unsigned long long)s.regions.load(), (unsigned long long)s.units_ready.load(),
               (unsigned long long)s.cache_hits.load(), (unsigned long long)s.compiles.load(), double(s.compile_us.load()) / 1000.0,
               (unsigned long long)s.failures.load(), (unsigned long long)s.corrupt.load(), (unsigned long long)s.regions_run.load(),
               (unsigned long long)s.instructions_run.load(), (unsigned long long)s.generated_run.load(), (unsigned long long)s.region_throws.load(), (unsigned long long)s.declined.load(),
               (unsigned long long)s.accepted.load(), (unsigned long long)s.continued.load());
  if (s.waits.load())   // (after the summary, and not a "jit: " line: what reads a statistics file takes its last "jit: " line for the summary)
    std::fprintf(out, "jit-wait: %llu sections waited on the plain loop for their threshold, %llu came back to count\n", (unsigned long long)s.waits.load(), (unsigned long long)s.wait_ends.load());
  if (s.prewaits.load())   // (round sp63)
    std::fprintf(out, "jit-prewait: %llu sections waited on the plain loop for their lookup\n", (unsigned long long)s.prewaits.load());
  if (s.history.load())
    std::fprintf(out, "jit-history: %llu sections compiled at their lookup the regions an earlier run chose\n", (unsigned long long)s.history.load());
  if (s.pch_used.load() || s.pch_built.load())   // (round sp64)
    std::fprintf(out, "jit-pch: %llu compiles read the precompiled runtime header, %llu made it\n", (unsigned long long)s.pch_used.load(), (unsigned long long)s.pch_built.load());
  for (const std::string& l : compile_log) std::fputs(l.c_str(), out);   // (round sp64)
  if (s.evicted.load())
    std::fprintf(out, "jit-cache: %llu objects and directories removed by the size cap and the age rule\n", (unsigned long long)s.evicted.load());
  if (out != stderr) std::fclose(out);
}

