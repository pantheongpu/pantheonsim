namespace {
// mkdir -p with mode 0700, then the checks of the leaf: a directory, ours, and writable by no one else.
std::string ensure_dir(const std::string& dir) {
  if (dir.empty()) return "no cache directory";
  for (size_t i = 1; i <= dir.size(); ++i) {
    if (i != dir.size() && dir[i] != '/') continue;
    const std::string pre = dir.substr(0, i);
    if (::mkdir(pre.c_str(), 0700) != 0 && errno != EEXIST) return "cannot create " + pre + ": " + std::strerror(errno);
  }
  struct stat st;
  if (::stat(dir.c_str(), &st) != 0) return "cannot stat " + dir + ": " + std::strerror(errno);
  if (!S_ISDIR(st.st_mode)) return dir + " is not a directory";
  if (st.st_uid != ::geteuid()) return dir + " is not owned by the user running the simulator";
  if (st.st_mode & 022) return dir + " is writable by others";
  return {};
}
}  // namespace

namespace {
std::string key_suffix(const Config& cfg, const std::string& cid, const std::string& isa) {
  static const std::string rt_hash = hash_text(std::string(kEmbeddedRuntime)) + hash_text(std::string(kEmbeddedKernels));
  return "\n//key: " + cid + " | isa " + isa + " | flags " + isa_flags(isa) + " | " + cfg.extra_flags + " | abi " + std::to_string(kAbiVersion) + " | gen " +
         std::to_string(kGeneratorVersion) + " | rt " + rt_hash + (cfg.link ? " | link" : "");   // (linking: its own objects and its own selections)
}
}  // namespace

std::string Engine::key(const UnitSpec& spec, std::string* why) {
  const std::string cid = compiler_id(why);
  if (cid.empty()) return {};
  const std::string isa = cfg_.isa.empty() ? detect_isa() : cfg_.isa;
  return hash_text(source(spec, isa == "avx2", cfg_.residence, cfg_.specialize, cfg_.link && !spec.nolink, cfg_.fuse) + key_suffix(cfg_, cid, isa));
}

// The key of a whole section (what the file naming its selection of regions is named by): the facts of every region, not their text.
std::string Engine::section_key(const UnitSpec& full, std::string* why) {
  const std::string cid = compiler_id(why);
  if (cid.empty()) return {};
  const std::string isa = cfg_.isa.empty() ? detect_isa() : cfg_.isa;
  const std::vector<uint32_t> m = meta(full);
  return hash_text(std::string(reinterpret_cast<const char*>(m.data()), m.size() * sizeof(uint32_t)) + key_suffix(cfg_, cid, isa));
}

UnitSpec Engine::subspec(const UnitSpec& spec, const std::vector<uint32_t>& sel) {
  UnitSpec out;
  out.sm = spec.sm;
  out.nolink = spec.nolink;
  for (uint32_t i : sel) out.regions.push_back(spec.regions[i]);
  return out;
}

// The span of a merged selection is bounded: a stop op costs no code, but the spec holds an element for it.
static constexpr uint32_t kMaxMergedSpan = 16384;

RegionSpec Engine::merge_regions(const UnitSpec& spec, const std::vector<uint32_t>& sel) {
  RegionSpec m;
  if (sel.empty()) return m;
  const RegionSpec& lastr = spec.regions[sel.back()];
  const uint32_t first = spec.regions[sel.front()].first, end = lastr.first + static_cast<uint32_t>(lastr.ops.size());
  m.first = first;
  OpFacts stop;
  stop.stop = true;
  m.ops.assign(end - first, stop);
  for (uint32_t i : sel) {
    const RegionSpec& r = spec.regions[i];
    for (size_t j = 0; j < r.ops.size(); ++j) {
      OpFacts o = r.ops[j];
      if (o.br) o.tgt += static_cast<int32_t>(r.first) - static_cast<int32_t>(first);   // (region-relative: to the merged region's first op)
      m.ops[r.first - first + j] = o;
    }
  }
  return m;
}

bool Engine::merges(const UnitSpec& spec, const std::vector<uint32_t>& sel) const {
  if (!cfg_.link || spec.nolink || sel.empty()) return false;
  // (VGPU_JIT_LINK_MERGE=0, a diagnostic of round sp53: linking with one function a region, as without it; what leaves one region for another goes through the host.)
  static const bool no_merge = [] {
    const char* v = std::getenv("VGPU_JIT_LINK_MERGE");
    return v && v[0] == '0' && !v[1];
  }();
  if (no_merge) return false;
  // (The regions must lie one after the other in the section, as make_unit's do: a spec whose regions carry no place is not merged.)
  uint64_t end = 0;
  for (size_t i = 0; i < sel.size(); ++i) {
    const RegionSpec& r = spec.regions[sel[i]];
    if (r.ops.empty() || (i && r.first < end)) return false;
    end = uint64_t{r.first} + r.ops.size();
  }
  return end - spec.regions[sel.front()].first <= kMaxMergedSpan;
}

UnitSpec Engine::selected_spec(const UnitSpec& full, const std::vector<uint32_t>& sel) const {
  if (!merges(full, sel)) return subspec(full, sel);
  UnitSpec out;
  out.sm = full.sm;
  out.nolink = full.nolink;
  out.regions.push_back(merge_regions(full, sel));
  return out;
}

Result Engine::lookup_selected(const UnitSpec& full, std::vector<uint32_t>* sel) {
  Result r;
  std::string why;
  const std::string skey = section_key(full, &why);
  if (skey.empty()) {
    r.status = Status::NoCompiler;
    r.message = why;
    return r;
  }
  {
    std::lock_guard<std::mutex> g(p_->mu);
    if (!p_->dir_checked) {
      p_->dir = cache_path();
      p_->dir_err = ensure_dir(p_->dir);
      p_->dir_checked = true;
    }
    if (!p_->dir_err.empty()) {
      r.status = Status::CacheUnusable;
      r.message = p_->dir_err;
      return r;
    }
  }
  std::string text;
  if (!read_file(cache_path() + "/" + skey + ".sel", text)) return r;   // nothing recorded: a miss
  std::vector<uint32_t> idx;
  {
    unsigned long n = 0;
    int off = 0;
    if (std::sscanf(text.c_str(), "VJSEL1 %lu%n", &n, &off) != 1 || n == 0 || n > full.regions.size()) return r;
    const char* q = text.c_str() + off;
    for (unsigned long k = 0; k < n; ++k) {
      unsigned long v = 0;
      int used = 0;
      if (std::sscanf(q, " %lu%n", &v, &used) != 1 || v >= full.regions.size() || (!idx.empty() && v <= idx.back())) return r;
      idx.push_back(static_cast<uint32_t>(v));
      q += used;
    }
  }
  const UnitSpec sub = selected_spec(full, idx);
  Result l = lookup(sub);
  if (sel && (l.found || l.status == Status::Ok)) *sel = idx;
  // (round sp63) A selection without its object: an earlier run chose these regions and its compile did not finish (cancelled at its exit, or the
  // object was evicted); the caller may compile them now rather than count to the threshold again.
  if (!l.found && l.status == Status::Ok) l.pending = true;
  return l;
}

// The selection is recorded before the compile (round sp63): a compile that does not finish -- the process ends first, and its compile is cancelled --
// leaves it behind, so that the next run of the program finds it at its lookup and compiles at once (Result::pending) instead of counting to the
// threshold again, and is warm from the run after. (Until then a program shorter than its compile never became warm: asyncAllocation, 3.2 s.)
Result Engine::obtain_selected(const UnitSpec& full, const std::vector<uint32_t>& sel) {
  const auto record = [&] {
    std::string why;
    const std::string skey = section_key(full, &why);
    {
      std::lock_guard<std::mutex> g(p_->mu);
      if (!p_->dir_checked) {
        p_->dir = cache_path();
        p_->dir_err = ensure_dir(p_->dir);
        p_->dir_checked = true;
      }
      if (!p_->dir_err.empty()) return;
    }
    std::string text = "VJSEL1 " + std::to_string(sel.size());
    for (uint32_t i : sel) text += " " + std::to_string(i);
    text += "\n";
    const std::string dir = cache_path();
    const std::string selp = dir + "/" + skey + ".sel";
    std::string have;
    if (!skey.empty() && !(read_file(selp, have) && have == text)) {
      const std::string tmp = dir + "/" + skey + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1)) + ".seltmp";
      if (!write_file(tmp, text) || ::rename(tmp.c_str(), selp.c_str()) != 0) ::unlink(tmp.c_str());   // (a failure only costs the next run its lookup)
    }
  };
  if (!mutant("history_after")) record();
  Result r = obtain(selected_spec(full, sel));
  if (r.found) record();
  return r;
}

// The two headers the generated code includes, in a directory of their own inside the cache, named by their hash: written (temp file and
// rename) if missing or different, so that what the compiler reads is, byte for byte, what is embedded in this binary.
std::string Engine::ensure_rt() {
  std::lock_guard<std::mutex> g(p_->mu);
  if (p_->rt_checked && p_->rt_err.empty()) return {};
  p_->rt_checked = true;
  const std::string dir = cache_path();
  const std::string rt = std::string(kEmbeddedRuntime), kn = std::string(kEmbeddedKernels);
  p_->rt_dir = dir + "/rt-" + hash_text(rt + "\n" + kn).substr(0, 16);
  p_->rt_err = ensure_dir(p_->rt_dir);
  if (!p_->rt_err.empty()) return p_->rt_err;
  const std::pair<const char*, const std::string*> files[] = {{"vgpu_jit_rt.h", &rt}, {"vgpu_jit_kernels.inc", &kn}};
  for (const auto& [name, text] : files) {
    const std::string path = p_->rt_dir + "/" + name;
    std::string have;
    if (read_file(path, have) && have == *text) continue;
    const std::string tmp = path + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1)) + ".tmp";
    if (!write_file(tmp, *text) || ::rename(tmp.c_str(), path.c_str()) != 0) {
      ::unlink(tmp.c_str());
      p_->rt_err = std::string("cannot write ") + path + ": " + std::strerror(errno);
      return p_->rt_err;
    }
  }
  return {};
}

Result Engine::load_(const UnitSpec& spec, const std::string& key, bool fresh) {
  Result r;
  r.key = key;
  const std::string dir = cache_path();
  const std::string so = dir + "/" + key + ".so", sum = dir + "/" + key + ".sum";
  std::string sumtext, bytes;
  if (!read_file(sum, sumtext) || !read_file(so, bytes)) return r;   // absent (or half written by a compile that has not finished): a miss
  {
    unsigned long long size = 0;
    char h[64] = {};
    if (std::sscanf(sumtext.c_str(), "%63s %llu", h, &size) != 2 || size != bytes.size() || hash_text(bytes) != h) {
      r.message = "the cached object " + key + " fails its checksum";
      r.replaced_corrupt = true;   // (the caller removes it, under the lock)
      return r;
    }
  }
  std::string err;
  void* h = cfg_.dlopen_fn ? cfg_.dlopen_fn(so.c_str(), &err) : ::dlopen(so.c_str(), RTLD_NOW | RTLD_LOCAL);
  if (!h) {
    if (!cfg_.dlopen_fn) {
      const char* e = ::dlerror();
      err = e ? e : "dlopen failed";
    }
    if (fresh) {
      r.status = Status::CacheUnusable;
      r.message = "cannot load an object just built in " + dir + " (is it mounted noexec?): " + err;
    } else {
      r.message = "the cached object " + key + " does not load: " + err;
      r.replaced_corrupt = true;
    }
    return r;
  }
  const auto bad = [&](const std::string& what) {
    if (!cfg_.dlopen_fn) ::dlclose(h);
    r.message = "the cached object " + key + ": " + what;
    if (fresh) r.status = Status::Mismatch;
    else r.replaced_corrupt = true;
    return r;
  };
  const uint32_t* mlen = static_cast<const uint32_t*>(::dlsym(h, "vgpu_jit_meta_len"));
  const uint32_t* mdat = static_cast<const uint32_t*>(::dlsym(h, "vgpu_jit_meta"));
  if (!mlen || !mdat) return bad("has no metadata");
  const std::vector<uint32_t> want = meta(spec);
  if (*mlen != want.size() || std::memcmp(mdat, want.data(), want.size() * sizeof(uint32_t)) != 0)
    return bad("was made for other instruction words, architecture or generator version");
  auto lib = std::make_shared<Loaded>();
  lib->handle = h;
  for (size_t i = 0; i < spec.regions.size(); ++i) {
    void* f = ::dlsym(h, ("vgpu_jit_r" + std::to_string(i)).c_str());
    if (!f) return bad("lacks region " + std::to_string(i));
    lib->fns.push_back(reinterpret_cast<RegionFn>(f));
  }
  r.lib = lib;
  r.found = true;
  r.hit = true;
  if (!fresh && !mutant("trim_no_touch")) {   // (use renews an object's time: the size cap removes the least recently used first)
    const struct timespec ts[2] = {{0, UTIME_OMIT}, {0, UTIME_NOW}};
    ::utimensat(AT_FDCWD, so.c_str(), ts, 0);
  }
  return r;
}

Result Engine::lookup(const UnitSpec& spec) {
  const auto t0 = Clock::now();
  Result r;
  std::string why;
  const std::string key = this->key(spec, &why);
  if (key.empty()) {
    r.status = Status::NoCompiler;
    r.message = why;
    return r;
  }
  {
    std::lock_guard<std::mutex> g(p_->mu);
    if (!p_->dir_checked) {
      p_->dir = cache_path();
      p_->dir_err = ensure_dir(p_->dir);
      p_->dir_checked = true;
    }
    if (!p_->dir_err.empty()) {
      r.status = Status::CacheUnusable;
      r.message = p_->dir_err;
      return r;
    }
  }
  r = load_(spec, key, false);
  r.lookup_ms = ms_since(t0);
  return r;
}

Result Engine::obtain(const UnitSpec& spec) {
  Result r = lookup(spec);
  if (r.found || r.status != Status::Ok) return r;
  const auto t0 = Clock::now();
  const std::string key = r.key;
  const std::string dir = cache_path();
  const bool damaged = r.replaced_corrupt;
  const int lockfd = ::open((dir + "/" + key + ".lock").c_str(), O_RDWR | O_CREAT | O_CLOEXEC, 0600);
  if (lockfd < 0) {
    r.status = Status::CacheUnusable;
    r.message = "cannot create a lock file in " + dir + ": " + std::strerror(errno);
    return r;
  }
  ::flock(lockfd, LOCK_EX);
  struct Unlock {
    int fd;
    ~Unlock() {
      ::flock(fd, LOCK_UN);
      ::close(fd);
    }
  } unlock{lockfd};
  // Another thread or process may have built it while this one waited.
  Result again = load_(spec, key, false);
  if (again.found) {
    again.replaced_corrupt = damaged;
    return again;
  }
  const std::string so = dir + "/" + key + ".so", sum = dir + "/" + key + ".sum";
  ::unlink(sum.c_str());
  ::unlink(so.c_str());   // (damaged, or half of a pair)
  Result out;
  out.key = key;
  out.replaced_corrupt = damaged || again.replaced_corrupt;
  const std::string stem = dir + "/" + key + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1));
  const std::string tmp_cpp = stem + ".cpp", tmp_so = stem + ".so";
  if (const std::string rterr = ensure_rt(); !rterr.empty()) {
    out.status = Status::CacheUnusable;
    out.message = rterr;
    return out;
  }
  const std::string isa = cfg_.isa.empty() ? detect_isa() : cfg_.isa;
  const std::string src = source(spec, isa == "avx2", cfg_.residence, cfg_.specialize, cfg_.link && !spec.nolink, cfg_.fuse);
  out.source_bytes = src.size();
  if (!write_file(tmp_cpp, src)) {
    out.status = Status::CacheUnusable;
    out.message = "cannot write to " + dir + ": " + std::strerror(errno);
    return out;
  }
  // The flags that are not the distribution's defaults (Ubuntu's compilers add a stack protector, stack-clash probes and control-flow instrumentation, which a region call of 10 to 30
  // ops pays for on every call: the canary and the probes of a frame of rows, an `endbr64` and `notrack` on the entry switch).
  std::vector<std::string> flags{"-std=c++20", "-O2", "-funroll-loops", "-I" + p_->rt_dir, "-fPIC", "-fexceptions", "-ffp-contract=off", "-fvisibility=hidden", "-w",
                                 "-fno-stack-protector", "-fno-stack-clash-protection"};
#if defined(__x86_64__)
  flags.push_back("-fcf-protection=none");
#endif
  for (const std::string& f : split_words(isa_flags(isa))) flags.push_back(f);
  for (const std::string& f : split_words(cfg_.extra_flags)) flags.push_back(f);
  // (Round sp64) The runtime header, precompiled. The generated source starts with the same four lines in every compile (two standard headers, the ISA
  // level, the runtime header with the lane kernels and <immintrin.h>), and parsing them is 0.35 to 0.43 s of every compile on server3 (<immintrin.h>
  // alone 0.29 s): half of a small section's compile (atomicAggregate 0.73 s, 0.36 s with it). GCC reads a header compiled once (`<name>.gch`, 53 MB)
  // in its place when the header is named with -include and the flags are the same; it ignores one that does not fit and reads the text, and the
  // object is the same bytes either way (checked on four sections). The header is made after the first compile of a process that found none, so
  // that no compile waits for it (build_pch); GCC only (clang has its own form), VGPU_JIT_PCH=0 turns it off.
  std::string pch_h;
  if (cfg_.pch && p_->cxx_id.find("clang") == std::string::npos) {
    const std::string first = "#include <cstddef>\n", last = "#include \"vgpu_jit_rt.h\"\n";
    const size_t a = src.find(first), b = src.find(last);
    if (a != std::string::npos && b != std::string::npos && b > a) {
      const std::string text = src.substr(a, b + last.size() - a);
      std::string ftext;
      for (const std::string& f : flags) ftext += f + "\n";
      const std::string h = p_->rt_dir + "/vgpu_jit_pch-" + hash_text(text + "|" + ftext + "|" + p_->cxx_id).substr(0, 16) + ".h";
      std::string have;
      struct stat gst;
      if (::stat((h + ".gch").c_str(), &gst) == 0 && read_file(h, have) && have == text) {
        pch_h = h;
      } else {
        std::lock_guard<std::mutex> g(p_->mu);
        if (!p_->pch_tried && p_->pch_h.empty()) {
          p_->pch_h = h;
          p_->pch_text = text;
          p_->pch_cmd.assign(1, p_->cxx_path);
          for (const std::string& f : flags) p_->pch_cmd.push_back(f);
        }
      }
    }
  }
  std::vector<std::string> cmd{p_->cxx_path};
  for (const std::string& f : flags) cmd.push_back(f);
  cmd.push_back("-shared");
  if (!pch_h.empty()) {
    cmd.push_back("-include");
    cmd.push_back(pch_h);
  }
  cmd.push_back("-o");
  cmd.push_back(tmp_so);
  cmd.push_back(tmp_cpp);
  Proc pr = run_process(cmd, cfg_.timeout_s * 1000u, cfg_.mem_mb, &p_->cancel);
  if (!pch_h.empty() && !pr.timed_out && !pr.cancelled && pr.rc != 0) {
    // (A precompiled header GCC cannot read -- damaged, half written by a process that died -- may fail the compile: it is removed, and the compile run without it.)
    ::unlink((pch_h + ".gch").c_str());
    cmd.erase(cmd.end() - 5, cmd.end() - 3);
    pch_h.clear();
    pr = run_process(cmd, cfg_.timeout_s * 1000u, cfg_.mem_mb, &p_->cancel);
  }
  out.pch = !pch_h.empty();
  if (std::getenv("VGPU_JIT_KEEP")) ::rename(tmp_cpp.c_str(), (dir + "/" + key + ".cpp").c_str());   // (debugging: keep the generated source)
  else ::unlink(tmp_cpp.c_str());
  out.compile_ms = ms_since(t0);
  compiles_.fetch_add(1);
  out.compiled = true;
  if (pr.timed_out || pr.cancelled || pr.rc != 0) {
    ::unlink(tmp_so.c_str());
    out.status = pr.timed_out ? Status::CompileTimeout : Status::CompileFailed;
    out.cancelled = pr.cancelled;
    out.message = pr.timed_out ? "the compile took more than " + std::to_string(cfg_.timeout_s) + " s and was killed"
                  : pr.cancelled ? "the compile was cancelled"
                                 : "the compiler failed (status " + std::to_string(pr.rc) + "): " + pr.out.substr(0, 600);
    return out;
  }
  std::string bytes;
  if (!read_file(tmp_so, bytes) || bytes.empty()) {
    ::unlink(tmp_so.c_str());
    out.status = Status::CompileFailed;
    out.message = "the compiler produced no object";
    return out;
  }
  const std::string sumtext = hash_text(bytes) + " " + std::to_string(bytes.size()) + "\n";
  // The object first, then its checksum: a reader that sees an object without a checksum takes it for a miss.
  if (::rename(tmp_so.c_str(), so.c_str()) != 0 || !write_file(stem + ".sum", sumtext) || ::rename((stem + ".sum").c_str(), sum.c_str()) != 0) {
    ::unlink(tmp_so.c_str());
    ::unlink((stem + ".sum").c_str());
    out.status = Status::CacheUnusable;
    out.message = "cannot install the object in " + dir + ": " + std::strerror(errno);
    return out;
  }
  Result fresh = load_(spec, key, true);
  if (fresh.found) trim(key);
  fresh.compiled = true;
  fresh.hit = false;
  fresh.compile_ms = out.compile_ms;
  fresh.source_bytes = out.source_bytes;
  fresh.pch = out.pch;
  fresh.replaced_corrupt = out.replaced_corrupt;
  if (!fresh.found) {
    ::unlink(sum.c_str());
    ::unlink(so.c_str());
    if (fresh.status == Status::Ok) fresh.status = Status::CacheUnusable;
  }
  return fresh;
}

// (Round sp64) Makes the precompiled runtime header the last compile found missing (obtain), once a process: the header's text in the runtime directory
// and its .gch, each written under a name of its own and renamed into place, so that a compile never reads half of one. Run by the manager after the
// object of that compile is published. True if one was made.
bool Engine::build_pch() {
  std::string h, text;
  std::vector<std::string> cmd;
  {
    std::lock_guard<std::mutex> g(p_->mu);
    if (p_->pch_tried || p_->pch_h.empty()) return false;
    p_->pch_tried = true;
    h = p_->pch_h;
    text = p_->pch_text;
    cmd = p_->pch_cmd;
  }
  const std::string stem = h + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1));
  std::string have;
  if (!(read_file(h, have) && have == text)) {
    if (!write_file(stem + ".tmp", text) || ::rename((stem + ".tmp").c_str(), h.c_str()) != 0) {
      ::unlink((stem + ".tmp").c_str());
      return false;
    }
  }
  const std::string gch = stem + ".gch.tmp";
  cmd.push_back("-x");
  cmd.push_back("c++-header");
  cmd.push_back("-o");
  cmd.push_back(gch);
  cmd.push_back(h);
  const Proc pr = run_process(cmd, cfg_.timeout_s * 1000u, cfg_.mem_mb, &p_->cancel);
  struct stat st;
  if (pr.timed_out || pr.cancelled || pr.rc != 0 || ::stat(gch.c_str(), &st) != 0 || st.st_size == 0 || ::rename(gch.c_str(), (h + ".gch").c_str()) != 0) {
    ::unlink(gch.c_str());
    return false;
  }
  return true;
}

