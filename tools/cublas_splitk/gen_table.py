#!/usr/bin/env python3
"""Turn the output of `split_probe survey` (one or more files, each line "in out m n k ta tb alpha beta L <L> slices <s>") into
nvidia/src/cublas_splitk_<card>.inc, the rows of the table cublas_splitk.hpp reads. Usage: gen_table.py <card name> <card text> <out.inc> <classify file> <survey files...>
The classify file is the output of tools/cublas_splitk/classify.cu on the card for the rows with m n k <= 2^25: S (the sum epilogue matches on random
data), A (the serial two-slice epilogue does), none (neither: the row is dropped). A row of more than 2^25 products was not run on random data: it
is kept with the sum epilogue when it has three slices or more, and dropped when it has two (which epilogue is not known)."""
import sys
card, text, out_path, class_path, files = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5:]
code = {('f16', 'f32'): 0, ('f16', 'f16'): 1, ('bf16', 'f32'): 2, ('bf16', 'f16'): 3, ('tf32', 'f32'): 4}
rows = {}
classified = {}
for line in open(class_path):
    p = line.split()
    classified[tuple(map(int, p[:6]))] = p[7]
for f in files:
    for line in open(f):
        p = line.split()
        if 'L' not in p or p[-1] != 'ok':   # refused, or "odd": the tree is not slices of chains (see nvidia/docs/cublas.md)
            continue
        i, o, m, n, k, ta, tb = p[0], p[1], int(p[2]), int(p[3]), int(p[4]), int(p[5]), int(p[6])
        if i == 'tf32' and m * n * k < 1 << 21:   # below cuBLAS's switch to the TF32 kernel (gemm_input_rounding.hpp): a plain FP32 kernel
            continue
        rows[(code[(i, o)], ta, tb, m, n, k)] = int(p[p.index('L') + 1])
lines = [
    "// Generated by tools/cublas_splitk/gen_table.py from `split_probe survey` run on " + text + ".",
    "// One row per product cuBLAS split over K: {type, ta, tb, m, n, k, L, serial}: slices of L products (the last one shorter), each a chain of tensor-core chunks",
    "// from zero, summed in order in f32 (serial: the two-slice epilogue of product_epilogue). type: 0 f16 -> f32, 1 f16 -> f16, 2 bf16 -> f32, 3 bf16 -> f16, 4 tf32 -> f32. Products of the grid m, n in",
    "// 32..1024 and k in 64..8192 that are not listed were measured unsplit, or are of another structure (nvidia/docs/cublas.md); products off the grid are not",
    "// known (the chain is used).",
]
dropped = 0
for key, L in sorted(rows.items()):
    if L >= key[5]:
        continue
    two = -(-key[5] // L) == 2
    cls = classified.get(key)
    if cls == 'none' or cls == 'refused' or (cls is None and two):
        dropped += 1
        continue
    lines.append("{%d,%d,%d,%d,%d,%d,%d,%d}," % (key + (L, 1 if cls == 'A' else 0)))
print('dropped', dropped)
open(out_path, 'w').write('\n'.join(lines) + '\n')
print(card, len(lines) - 5, 'split rows of', len(rows))
