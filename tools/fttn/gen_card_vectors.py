#!/usr/bin/env python3
"""Pick fixed test vectors out of a card's tensor-core dump (see fit_tc_model.py for the dump): results with finite operands on which
the given rule and a second rule differ, so that a unit test built from them tells the two apart.

  gen_card_vectors.py <dump-dir> <rule> <other-rule> <per-form> "<card, driver, toolkit, date>" > tests/unit/tcNN_card_vectors.inc

Lines are {kind (0 f16, 1 bf16, 2 tf32), K, chunk, acc_f16, a[K] as float bits, b[K], c bits, d bits (an f16 accumulator: the f16
value as float bits)}, the format of tests/unit/tc86_card_vectors.inc. Every line is the card's own result; the script refuses a
dump the rule does not reproduce.
"""
import sys

import numpy as np

import fit_tc_model as fit


def main():
    d, rule, other, per_form, what = sys.argv[1], fit.parse_rule(sys.argv[2]), fit.parse_rule(sys.argv[3]), int(sys.argv[4]), sys.argv[5]
    print(f'// Generated by tools/fttn/gen_card_vectors.py from {what}: wmma results with finite operands on which')
    print(f'// the rule "{sys.argv[2]}" (the card\'s) and "{sys.argv[3]}" differ.')
    print('// {kind, K, chunk, acc_f16, a[K] as float bits, b[K], c bits, d bits (an f16 accumulator: the f16 value as float bits)}')
    f32bits = lambda x: int(np.float32(x).view(np.uint32))
    total = 0
    for form in fit.FORMS:
        kind = 0 if 'f16_' in form and 'bf16' not in form else 1 if 'bf16' in form else 2
        picked = 0
        for style in ('random', 'edges'):
            with np.errstate(invalid='ignore'):
                A, B, C, res, emin, sig, acc16, tiles = fit.operands(d, form, style, 0, 4096)
            chunk = rule['chunk'] if kind != 2 else min(rule['chunk'], 4)
            ochunk = other['chunk'] if kind != 2 else min(other['chunk'], 4)
            fin = np.isfinite(A).all(axis=1) & np.isfinite(B).all(axis=1) & np.isfinite(C)
            idx = np.nonzero(fin)[0]
            A, B, C, res = A[idx], B[idx], C[idx], res[idx]
            got, _ = fit.model(A, B, C, emin, sig, chunk, rule['grid'], rule['cut'], rule['final'], acc16)
            alt, _ = fit.model(A, B, C, emin, sig, ochunk, other['grid'], other['cut'], other['final'], acc16)
            if acc16:
                cardv = res.astype(np.uint16).view(np.float16).astype(np.float64)
            else:
                cardv = res.astype(np.uint32).view(np.float32).astype(np.float64)
            if not np.array_equal(np.nan_to_num(got, nan=1e300), np.nan_to_num(cardv, nan=1e300)):
                sys.exit(f'{form} {style}: the rule does not reproduce this dump')
            want = np.nonzero((got != alt) & np.isfinite(cardv))[0]
            for i in want[: max(0, per_form - picked)]:
                K = A.shape[1]
                a = ', '.join('0x%08xu' % f32bits(x) for x in A[i])
                b = ', '.join('0x%08xu' % f32bits(x) for x in B[i])
                print('{%d, %d, %d, %d, {%s}, {%s}, 0x%08xu, 0x%08xu},' % (kind, K, chunk, int(acc16), a, b, f32bits(C[i]), f32bits(cardv[i])))
                picked += 1
        total += picked
        print(f'// {form}: {picked}', file=sys.stderr)
    print(f'// total {total}', file=sys.stderr)


if __name__ == '__main__':
    main()
