#!/usr/bin/env python3
"""Writes tests/unit/tc_fp8_card_vectors.inc: from the Ada (RTX 1000 Ada) e4m3 / e5m2 files of Khattak and Mikaitis (khattak_convert.py's
output, BSD-2-Clause, github.com/north-numerical-computing/MATLAB-tensor-core), the first N vectors in each of the four files (f32 and
f16 accumulator) on which the sequential sum in the accumulator's format gives another bit pattern than the card did.

  fp8_unit_vectors.py <vectors dir> <N> > tests/unit/tc_fp8_card_vectors.inc

Our own script; run it with python3 -I.
"""
import struct, sys

def f32(x): return struct.unpack("<f", struct.pack("<f", x))[0]
def f16(x):
    try: return struct.unpack("<e", struct.pack("<e", x))[0]
    except OverflowError: return float("inf") if x > 0 else float("-inf")
def val(h): return struct.unpack("<f", struct.pack("<I", int(h, 16)))[0]

def main():
    d, n = sys.argv[1], int(sys.argv[2])
    print("// Generated by tools/tcpapers/fp8_unit_vectors.py from the Ada files of Khattak and Mikaitis, \"Accurate Models of NVIDIA Tensor Cores\" (arXiv 2512.07004),")
    print("// github.com/north-numerical-computing/MATLAB-tensor-core, model_validation/, commit 79143bd (BSD 2-Clause, Copyright (c) 2025 Faizan A. Khattak and")
    print("// Mantas Mikaitis; the notice is nvidia/tests/data/tcpapers/NOTICE). Vectors recorded on an RTX 1000 Ada where the sequential sum in the accumulator's")
    print("// format gives another result.  {format (0 e4m3, 1 e5m2), f16 accumulator, a[32], b[32] as float bits, c bits, d bits}")
    for fmt, code in (("e4m3", 0), ("e5m2", 1)):
        for o in ("fp32", "fp16"):
            got = 0
            for line in open(f"{d}/Ada.{fmt}.{o}.txt"):
                t = line.split()
                a, b, c, dd = [val(x) for x in t[:32]], [val(x) for x in t[32:64]], val(t[64]), val(t[65])
                if any(x != x or abs(x) == float("inf") for x in a + b + [c, dd]): continue
                acc = f16(c) if o == "fp16" else c
                for x, y in zip(a, b):
                    acc = f16(acc + x * y) if o == "fp16" else f32(acc + f32(x * y))
                if struct.pack("<f", acc) == struct.pack("<f", dd): continue
                print("{%d, %d, {%s}, {%s}, 0x%su, 0x%su}," % (code, o == "fp16", ", ".join("0x%su" % x for x in t[:32]), ", ".join("0x%su" % x for x in t[32:64]), t[64], t[65]))
                got += 1
                if got == n: break

main()
