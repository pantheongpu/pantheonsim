#!/usr/bin/env python3
"""Writes tests/unit/tc_fp8_wgmma_vectors.inc: from the H100 and H200 e4m3 / e5m2 f32-accumulator files of Khattak and Mikaitis
(khattak_convert.py's output, BSD-2-Clause, github.com/north-numerical-computing/MATLAB-tensor-core), the first N vectors of each of
the four files on which the sequential f32 sum gives another bit pattern than the card did. The paper recorded these through wgmma with
a zero accumulator, so c is not an input.

  fp8_wgmma_vectors.py <vectors dir> <N> > tests/unit/tc_fp8_wgmma_vectors.inc

Our own script; run it with python3 -I.
"""
import struct, sys

def f32(x): return struct.unpack("<f", struct.pack("<f", x))[0]
def val(h): return struct.unpack("<f", struct.pack("<I", int(h, 16)))[0]

def main():
    d, n = sys.argv[1], int(sys.argv[2])
    print("// Generated by tools/tcpapers/fp8_wgmma_vectors.py from the H100 and H200 files of Khattak and Mikaitis, \"Accurate Models of NVIDIA Tensor Cores\" (arXiv 2512.07004),")
    print("// github.com/north-numerical-computing/MATLAB-tensor-core, model_validation/, commit 79143bd (BSD 2-Clause, Copyright (c) 2025 Faizan A. Khattak and")
    print("// Mantas Mikaitis; the notice is nvidia/tests/data/tcpapers/NOTICE). Recorded through wgmma with a zero accumulator, where the sequential f32 sum gives another")
    print("// result.  {format (0 e4m3, 1 e5m2), a[32], b[32] as float bits, d bits}")
    for card in ("H100", "H200"):
        for fmt, code in (("e4m3", 0), ("e5m2", 1)):
            got = 0
            for line in open(f"{d}/{card}.{fmt}.fp32.txt"):
                t = line.split()
                a, b, dd = [val(x) for x in t[:32]], [val(x) for x in t[32:64]], val(t[65])
                if any(x != x or abs(x) == float("inf") for x in a + b + [dd]): continue
                acc = 0.0
                for x, y in zip(a, b): acc = f32(acc + f32(x * y))
                if struct.pack("<f", acc) == struct.pack("<f", dd): continue
                print("{%d, {%s}, {%s}, 0x%su}," % (code, ", ".join("0x%su" % x for x in t[:32]), ", ".join("0x%su" % x for x in t[32:64]), t[65]))
                got += 1
                if got == n: break

main()
