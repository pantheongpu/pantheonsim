#!/usr/bin/env python3
"""Builds amd/src/rdna2_trans_data.inc: the RX 6800's v_rcp_f32, v_rsq_f32 and v_sqrt_f32 on the mantissas of one binade, as a cubic per
segment plus a list of the mantissas where the card's result is one unit away from the cubic's (docs/numerics/math-functions.md, "AMD").

Input: the card's results over one binade of inputs, five dumps (little-endian uint32, 2^23 results each), written by
  amd_trans_probe RCP  dump 3f800000 8388608 > rcp.bin        x in [1, 2)
  amd_trans_probe RSQ  dump 3f800000 8388608 > rsq0.bin       x in [1, 2)     (an even exponent)
  amd_trans_probe RSQ  dump 40000000 8388608 > rsq1.bin       x in [2, 4)     (an odd exponent)
  amd_trans_probe SQRT dump 3f800000 8388608 > sqrt0.bin
  amd_trans_probe SQRT dump 40000000 8388608 > sqrt1.bin
Usage: amd_trans_table_fit.py rcp.bin rsq0.bin rsq1.bin sqrt0.bin sqrt1.bin > amd/src/rdna2_trans_data.inc      (needs numpy; a minute)

The model of one table (the same arithmetic as amd/src/rdna2_trans.hpp, which is what the test checks): m is the 23-bit mantissa; segment s = m >> 18
(32 segments), f = m & 0x3ffff, fq = f with its j low bits cleared (the card's squarer drops them: measured, the earlier attempts of
2026-11-16); acc = c0 + c1 f + c2 fq^2 + c3 f^3 (a 128-bit integer, the coefficients scaled by 2^96); y = y0 + floor(acc / 2^96);
where the mantissa is on the exception list, y changes by +1 when the fraction of acc is half or more, by -1 otherwise (checked here for
every entry). y is the result's bits minus the table's base. m = 0 is a stored constant. Our own code."""
import base64
import sys
import numpy as np

N = 1 << 18
S = 96
NAMES = ["Rcp", "Rsq0", "Rsq1", "Sqrt0", "Sqrt1"]


def fit_table(bits, j):
    base = (int(bits[1]) >> 23) << 23
    y = bits.astype(np.int64) - base
    assert y[1:].min() >= 0 and y[1:].max() < (1 << 23), "a result leaves its binade"
    segs, mism_total, exc = [], 0, []
    for s in range(32):
        lo = 1 if s == 0 else 0
        f = np.arange(lo, N)
        ys = y[s * N + lo:(s + 1) * N].astype(np.float64)
        yref = int(ys[0])
        t = f / N
        fq = ((f >> j) << j) / N
        a = np.stack([np.ones(len(f)), t, fq ** 2, t ** 3], 1)
        c, *_ = np.linalg.lstsq(a, ys - yref + 0.5, rcond=None)
        # fixed point: acc = c0 + c1 f + c2 fq^2 + c3 f^3, each scaled by 2^96 (f and fq are integers, not fractions)
        ci = [int(round(float(c[0]) * 2.0 ** S)), int(round(float(c[1]) * 2.0 ** (S - 18))), int(round(float(c[2]) * 2.0 ** (S - 36))), int(round(float(c[3]) * 2.0 ** (S - 54)))]
        segs.append((yref, ci))
        yi = ys.astype(np.int64)
        for fi, want in zip(range(lo, N), yi):
            fqi = (fi >> j) << j
            acc = ci[0] + ci[1] * fi + ci[2] * fqi * fqi + ci[3] * fi * fi * fi
            got = yref + (acc >> S)
            if got != want:
                up = (acc >> (S - 1)) & 1
                assert want == got + (1 if up else -1), f"exception of {abs(want - got)} units at {s * N + fi}"
                exc.append(s * N + fi)
    return base, int(y[0]), segs, exc


def encode_gaps(exc):
    out, prev = bytearray(), 0
    for m in exc:
        g = m - prev - 1
        prev = m
        while g >= 128:
            out.append(128 | (g & 127))
            g >>= 7
        out.append(g)
    return bytes(out)


def main():
    files = sys.argv[1:]
    assert len(files) == 5
    print("// Generated by tools/numerics/amd_trans_table_fit.py from an RX 6800's results (gfx1030, ROCm 7.2.0); see that file and docs/numerics/math-functions.md.")
    print("// Do not edit. One block a table: the squarer's cleared bits, the base, the result at m = 0, 32 segments {y0, c0..c3 as hi, lo words}, the exception gaps.")
    for name, fn in zip(NAMES, files):
        bits = np.fromfile(fn, dtype="<u4")[:1 << 23]
        best = None
        for j in (1, 2):
            sys.stderr.write(f"{name} j={j}\n")
            r = fit_table(bits, j)
            if best is None or len(r[3]) < len(best[1][3]):
                best = (j, r)
        j, (base, y0m, segs, exc) = best
        sys.stderr.write(f"{name}: j={j}, {len(exc)} exceptions\n")
        print(f"inline constexpr unsigned k{name}J = {j};")
        print(f"inline constexpr uint32_t k{name}Base = 0x{base:08x}u;")
        print(f"inline constexpr int32_t k{name}AtZero = {y0m};")
        print(f"inline constexpr uint32_t k{name}ExcCount = {len(exc)};")
        print(f"inline constexpr Seg k{name}Seg[32] = {{")
        for yref, ci in segs:
            words = []
            for v in ci:
                u = v & ((1 << 128) - 1)
                words.append(f"{{0x{u >> 64:016x}ull, 0x{u & ((1 << 64) - 1):016x}ull}}")
            print(f"    {{{yref}, {{{', '.join(words)}}}}},")
        print("};")
        b64 = base64.b64encode(encode_gaps(exc)).decode()
        print(f"inline constexpr char k{name}Exc[] =")
        for i in range(0, len(b64), 100):
            print(f'    "{b64[i:i + 100]}"')
        print(";")


if __name__ == "__main__":
    main()
