#!/usr/bin/env python3
"""Generates random floating-point kernels with LLNL's Varity (tools/numerics/varity/fetch.sh) for a differential run.

    gen.py <varity-dir> <out-dir> [--programs 150] [--inputs 3] [--seed 20261115] [--math 0.25]

Varity writes the compute() function and draws its inputs; this script fixes the seed (one per program, so a program does
not depend on how many were generated before it) and writes the program around the function itself, because Varity's own
CUDA output passes host arrays to the kernel and prints from the device:

  <out>/d_0001.cu ... (double), f_0001.cu ... (float)   compute() as a kernel that stores its result, arrays on the device,
                                                        built by nvcc or hipcc with -I tools/numerics (gpu_api.h)
  <out>/d_0001.inputs ...                               one input set a line; the program takes the file and prints, per
                                                        line, the result as %.17g and its bits

--math is Varity's MATH_FUNC_PROBABILITY (its default is 0.05; raised here because math functions are what is compared).
"""
import os
import random
import sys


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    varity, out = argv[0], argv[1]
    opts = {'--programs': 150, '--inputs': 3, '--seed': 20261115, '--math': 0.25}
    i = 2
    while i < len(argv):
        if argv[i] not in opts or i + 1 >= len(argv):
            print(__doc__)
            return 2
        opts[argv[i]] = type(opts[argv[i]])(argv[i + 1])
        i += 2
    sys.path.insert(0, os.path.join(varity, 'varity'))
    sys.path.insert(0, os.path.join(varity, 'varity', 'common'))
    import cfg
    import gen_inputs
    import gen_program
    import id_generator
    import type_checking
    cfg.MATH_FUNC_PROBABILITY = opts['--math']
    os.makedirs(out, exist_ok=True)
    for real in ('double', 'float'):
        cfg.REAL_TYPE = real
        bits = 'unsigned long long' if real == 'double' else 'unsigned int'
        for n in range(1, opts['--programs'] + 1):
            random.seed('%d/%s/%d' % (opts['--seed'], real, n))
            program = gen_program.Program()
            func = program.func.printCode()
            head, tail = 'void compute(', 'printf("%.17g\\n", comp);'
            if func.count(head) != 1 or func.count(tail) != 1:
                raise SystemExit('unexpected Varity output for %s %d' % (real, n))
            func = func.replace(head, 'void compute(%s* result_, ' % real).replace(tail, '*result_ = comp;')
            types = [real] + list(id_generator.IdGenerator.get().getVarsList().values())   # comp, then the variables in order
            decl, args, parse = [], [], []
            for k, t in enumerate(types):
                if type_checking.isTypeReal(t):
                    decl.append('    %s a%d = (%s)atof(tok[%d]);' % (real, k, real, k))
                    args.append('a%d' % k)
                elif type_checking.isTypeInt(t):
                    decl.append('    int a%d = atoi(tok[%d]);' % (k, k))
                    args.append('a%d' % k)
                else:   # an array, filled with one value
                    decl.append('    for (int j = 0; j < %d; ++j) fill[j] = (%s)atof(tok[%d]);' % (cfg.ARRAY_SIZE, real, k))
                    decl.append('    gpuMemcpy(arr[%d], fill, sizeof fill, gpuToDevice);' % k)
                    args.append('arr[%d]' % k)
            name = '%s_%04d' % (real[0], n)
            with open(os.path.join(out, name + '.cu'), 'w') as f:
                f.write('''// Generated by tools/numerics/varity/gen.py with LLNL Varity (seed %(seed)d, %(real)s, program %(n)d). Do not edit.
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include "gpu_api.h"

__global__
%(func)s

int main(int argc, char** argv) {
  if (argc < 2) return 2;
  FILE* in = fopen(argv[1], "r");
  if (!in) return 2;
  %(real)s* arr[%(nargs)d]; %(real)s fill[%(asize)d]; %(real)s* dres;
  for (int k = 0; k < %(nargs)d; ++k) gpuMalloc(&arr[k], sizeof fill);
  gpuMalloc(&dres, sizeof(%(real)s));
  char line[4096];
  for (int set = 0; fgets(line, sizeof line, in); ++set) {
    char* tok[%(nargs)d]; int nt = 0;
    for (char* t = strtok(line, " \\n"); t && nt < %(nargs)d; t = strtok(nullptr, " \\n")) tok[nt++] = t;
    if (nt != %(nargs)d) continue;
%(decl)s
    %(real)s res = 0;
    gpuMemcpy(dres, &res, sizeof res, gpuToDevice);
    compute<<<1, 1>>>(dres, %(args)s);
    if (gpuSync() != gpuOk) { printf("%(name)s.%%d FAILED\\n", set); continue; }
    gpuMemcpy(&res, dres, sizeof res, gpuToHost);
    %(bits)s u; memcpy(&u, &res, sizeof u);
    printf("%(name)s.%%d %%.17g %%0%(hex)dllx\\n", set, (double)res, (unsigned long long)u);
  }
  return 0;
}
''' % {'seed': opts['--seed'], 'real': real, 'n': n, 'func': func, 'nargs': len(types), 'asize': cfg.ARRAY_SIZE,
       'decl': '\n'.join(decl), 'args': ', '.join(args), 'bits': bits, 'name': name, 'hex': 16 if real == 'double' else 8})
            with open(os.path.join(out, name + '.inputs'), 'w') as f:
                for _ in range(opts['--inputs']):
                    vals = []
                    for t in types:
                        vals.append('5' if type_checking.isTypeInt(t) else gen_inputs.InputGenerator.genInput())
                    f.write(' '.join(vals) + '\n')
    print('%d double and %d float programs in %s' % (opts['--programs'], opts['--programs'], out))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
