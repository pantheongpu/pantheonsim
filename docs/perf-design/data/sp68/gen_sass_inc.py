#!/usr/bin/env python3
# Turns cuobjdump -sass listings of own kernels (nvcc 13.0 and 13.2, sm_86, Round sp67's dumps) into C++ arrays of {pc, lo, hi} for the unit test.
# Checks that the 13.2 words equal the 13.0 words for every kernel taken.
import re, sys
root = sys.argv[1]
take = [("GRAMSCHM", "_Z19gramschmidt_kernel1iiPfS_S_i", "kGramschmidtKernel1"),
        ("GRAMSCHM", "_Z19gramschmidt_kernel2iiPfS_S_i", "kGramschmidtKernel2"),
        ("CORR", "_Z10std_kerneliiPfS_S_", "kCorrStdKernel"),
        ("sfu_exhaustive", "_Z3runijmmmbPj", "kProbeRun")]
def words(path, fn):
    lines = open(path).read().split('\n')
    out, on = [], False
    for k, l in enumerate(lines):
        if 'Function :' in l:
            on = l.split('Function :')[1].strip() == fn
            continue
        if not on: continue
        m = re.search(r'/\*([0-9a-f]{4})\*/\s+(.*?)\s*;\s*/\* (0x[0-9a-f]{16}) \*/', l)
        if m:
            hi = re.search(r'/\* (0x[0-9a-f]{16}) \*/', lines[k + 1]).group(1)
            out.append((int(m.group(1), 16), m.group(3), hi, m.group(2).strip()))
    # drop the tail of padding (the self-branch and the NOPs after the last instruction)
    while out and (out[-1][3] == 'NOP' or re.match(r'BRA 0x%x$' % out[-1][0], out[-1][3])): out.pop()
    return out
print("// Generated by docs/perf-design/data/sp68/gen_sass_inc.py from cuobjdump -sass of own kernels built with nvcc 13.0.88 -arch=sm_86 (Round sp67's dumps);")
print("// nvcc 13.2.51 gives the same words for every kernel here (checked by the generator). {pc, low word, high word}, with the instruction as text.")
for prog, fn, name in take:
    a = words(f"{root}/13.0/{prog}.sass", fn)
    b = words(f"{root}/13.2/{prog}.sass", fn)
    assert [x[:3] for x in a] == [x[:3] for x in b], (prog, fn)
    assert a, fn
    print(f"// {prog} {fn}")
    print(f"static const SassWord {name}[] = {{")
    for pc, lo, hi, t in a:
        print(f"    {{0x{pc:04x}, {lo}ull, {hi}ull}},   // {t}")
    print("};")
