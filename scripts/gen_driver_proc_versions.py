#!/usr/bin/env python3
"""Makes the table cuGetProcAddress resolves a driver function's name by (nvidia/src/driver_proc_versions.inc).

A caller asks the driver for a function by its base name and the CUDA version whose ABI it was written against
(cuGraphExecUpdate at 12000), and the driver answers with the export that has that ABI (cuGraphExecUpdate_v2).
NVIDIA's typedef headers name every ABI a function has had: PFN_cuGraphExecUpdate_v10020 and
PFN_cuGraphExecUpdate_v12000, PFN_cuMemcpyHtoD_v7000_ptds for the per-thread-stream form. Sorted by version, the
first ABI is the plain name and the n-th is <name>_v<n> (cuCtxCreate: 2000, 3020, 11040, 12050 are cuCtxCreate,
_v2, _v3, _v4); a _ptsz / _ptds typedef says from which version the per-thread form of the ABI current then exists.
That rule reproduces an RTX 3060's driver for every name the headers give, at 11040, 12000, 12040 and 13000, in both
stream modes (nvidia/tests/data/driver_proc_address.rtx3060.txt, test_driver_proc_address).

The rows are names and version numbers only, so the table is kept in the tree and the build needs no toolkit.

usage: gen_driver_proc_versions.py <cuda include dir> [<out.inc>]   write the table (default: the one in the tree)
       gen_driver_proc_versions.py --check <cuda include dir>        every row those headers give is in the table
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "nvidia" / "src" / "driver_proc_versions.inc"
HEADERS = ["cudaTypedefs.h", "cudaGLTypedefs.h", "cudaEGLTypedefs.h", "cudaVDPAUTypedefs.h", "cudaProfilerTypedefs.h"]
KIND = {None: 0, "_ptsz": 1, "_ptds": 2}
PFN = re.compile(r"\bPFN_(cu\w+?)_v(\d+)(_ptsz|_ptds)?\s*\)")
ROW = re.compile(r'^\{"(cu\w+)", (\d+), (\d)\},$')


def rows_from(include):
    rows = set()
    found = False
    for h in HEADERS:
        p = pathlib.Path(include) / h
        if not p.exists():
            continue
        found = True
        for m in PFN.finditer(p.read_text(errors="replace")):
            rows.add((m.group(1), int(m.group(2)), KIND[m.group(3)]))
    return rows if found else None


def rows_in_tree():
    rows = set()
    for line in OUT.read_text().splitlines():
        m = ROW.match(line)
        if m:
            rows.add((m.group(1), int(m.group(2)), int(m.group(3))))
    return rows


def main(argv):
    if argv[:1] == ["--check"]:
        if len(argv) < 2 or not argv[1]:
            print("SKIP: no CUDA include directory")
            return 0
        rows = rows_from(argv[1])
        if rows is None:
            print(f"SKIP: no cudaTypedefs.h in {argv[1]}")
            return 0
        missing = sorted(rows - rows_in_tree())
        for r in missing:
            print(f"  not in driver_proc_versions.inc: PFN_{r[0]}_v{r[1]}{['', '_ptsz', '_ptds'][r[2]]}")
        if missing:
            print(f"FAIL: {len(missing)} ABI(s) the headers in {argv[1]} name are missing; rerun scripts/gen_driver_proc_versions.py")
            return 1
        print(f"PASS: every ABI the headers in {argv[1]} name is in driver_proc_versions.inc")
        return 0
    if not argv:
        print(__doc__)
        return 2
    rows = rows_from(argv[0])
    if rows is None:
        print(f"no cudaTypedefs.h in {argv[0]}", file=sys.stderr)
        return 1
    out = pathlib.Path(argv[1]) if len(argv) > 1 else OUT
    lines = [
        "// Generated by scripts/gen_driver_proc_versions.py from the CUDA toolkit's typedef headers; do not edit.",
        "// {name, CUDA version, kind}: kind 0 is an ABI of the name (PFN_<name>_v<version>), 1 and 2 the version from",
        "// which its per-thread-stream form exists (PFN_<name>_v<version>_ptsz / _ptds).",
    ]
    lines += ['{"%s", %d, %d},' % r for r in sorted(rows)]
    out.write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
