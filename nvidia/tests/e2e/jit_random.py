#!/usr/bin/env python3
"""Writes a CUDA program of random straight-line kernels for the JIT's differential test (run_sass_jit.sh).

Each kernel is a few dozen statements over a small pool of u32 / u64 / float variables (so values are reused, a destination is often a
source, 64-bit pairs and carries are made from the same variables), some under `if` guards on a lane-dependent condition, some reading
memory (the escapes of a region), with inputs that are special values mixed with random bits. The program prints a hash of each kernel's
results for blocks of 128, 48 and 33 threads; run_sass_jit.sh requires the same output from the tier and from the JIT with every region
compiled (and the counters, which the shim prints with VGPU_COUNTERS=1). usage: jit_random.py <seed> <kernels> > file.cu
"""
import random
import sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
nk = int(sys.argv[2]) if len(sys.argv) > 2 else 24
R = random.Random(seed)
NV = 10   # u32 variables v0..v9
NF = 4    # float variables f0..f3
NW = 3    # u64 variables w0..w2

def v(): return "v%d" % R.randrange(NV)
def f(): return "f%d" % R.randrange(NF)
def w(): return "w%d" % R.randrange(NW)
def imm(): return R.choice(["0u", "1u", "31u", "32u", "0xffffffffu", "0x80000000u", "0x7fffffffu", "0x9e3779b9u", "%du" % R.randrange(1, 1000), "0x%08xu" % R.getrandbits(32)])
def src():
    r = R.randrange(10)
    return imm() if r < 2 else ("-" + v() if r == 2 else ("~" + v() if r == 3 else v()))

def stmt():
    k = R.randrange(30)
    d = v()
    if k == 0: return "%s = %s + %s + %s;" % (d, src(), src(), src())
    if k == 1: return "%s = %s * %s + %s;" % (d, v(), src(), src())
    if k == 2: return "%s = (%s & %s) ^ ~%s;" % (d, v(), src(), v())
    if k == 3: return "%s = %s << (%s & 31u);" % (d, v(), src())
    if k == 4: return "%s = %s >> (%s %% 40u);" % (d, v(), src())
    if k == 5: return "%s = (u32)((i32)%s >> (%s & 31u));" % (d, v(), src())
    if k == 6: return "%s = __funnelshift_l(%s, %s, %s);" % (d, v(), v(), src())
    if k == 7: return "%s = __funnelshift_rc(%s, %s, %s);" % (d, v(), v(), src())
    if k == 8: return "%s = __byte_perm(%s, %s, %s);" % (d, v(), v(), src())
    if k == 9: return "%s = min(%s, %s);" % (d, v(), src())
    if k == 10: return "%s = (u32)max((i32)%s, (i32)%s);" % (d, v(), v())
    if k == 11: return "%s = (%s < %s) ? %s : %s;" % (d, v(), src(), v(), v())
    if k == 12: return "%s = ((i32)%s >= (i32)%s) ? %s : %s;" % (d, v(), v(), src(), v())
    if k == 13:
        x = w()
        return "%s = (u64)%s * %s + %s; %s = (u32)%s; %s = (u32)(%s >> 32);" % (x, v(), v(), v(), d, x, v(), x)
    if k == 14:
        x = w()
        return "%s = ((u64)%s << 32 | %s) + ((u64)%s << 32 | %s); %s = (u32)(%s >> 32);" % (x, v(), v(), v(), v(), d, x)
    if k == 15: return "%s = %s + %s; %s = %s + (%s < %s);" % (d, v(), v(), v(), v(), d, v())
    if k == 16: return "%s = __umulhi(%s, %s);" % (d, v(), v())
    if k == 17: return "%s = (u32)__mulhi((i32)%s, (i32)%s);" % (d, v(), v())
    if k == 18: return "if (%s & %du) %s = %s + %s;" % (v(), 1 << R.randrange(6), d, v(), src())
    if k == 19: return "if (!(%s & %du)) %s = %s ^ %s;" % (v(), 1 << R.randrange(6), d, v(), src())
    if k == 20: return "if ((lane + %s) %% 3u == 0) %s = %s * 5u + %s;" % (v(), d, v(), v())
    if k == 21: return "%s = %s + (u32)(%s < %s) + (u32)(%s == %s);" % (d, v(), v(), v(), v(), src())
    if k == 22: return "%s = __float_as_uint(fmaf(%s, %s, %s));" % (d, "__uint_as_float(%s)" % v(), "__uint_as_float(%s)" % v(), "__uint_as_float(%s)" % v())
    if k == 23: return "%s = fmaf(%s, %s, %s);" % (f(), f(), f(), f())
    if k == 24: return "%s = %s + %s * %s;" % (f(), f(), f(), "__uint_as_float(%s)" % v())
    if k == 25: return "%s = (float)%s * 0.5f + %s;" % (f(), v(), f())
    if k == 26: return "%s = __float_as_uint(%s) ^ %s;" % (d, f(), v())
    if k == 27: return "%s ^= in[(%s) & 255u];" % (d, v())          # a load: an escape inside the region
    if k == 28: return "%s = (%s > %s) ? __float_as_uint(%s) : %s;" % (d, v(), src(), f(), v())
    return "%s = %s - %s;" % (d, v(), v())

print("// generated by jit_random.py, seed %d" % seed)
print('#include <cstdint>\n#include <cstdio>\n#include <vector>\n#include <cuda_runtime.h>')
print("typedef uint32_t u32; typedef uint64_t u64; typedef int32_t i32;")
print("#define CK(x) do { cudaError_t e_ = (x); if (e_) { std::printf(\"error %s at line %d\\n\", cudaGetErrorString(e_), __LINE__); return 1; } } while (0)")
print("constexpr int NV = %d, NF = %d, NO = %d;" % (NV, NF, NV + NF))
for k in range(nk):
    n = R.randrange(24, 90)
    print("__global__ void k%d(const u32* in, u32* out, int n) {" % k)
    print("  int t = blockIdx.x * blockDim.x + threadIdx.x; if (t >= n) return;")
    print("  u32 lane = threadIdx.x & 31u;")
    for i in range(NV): print("  u32 v%d = in[(t * %d + %d) & 255u] ^ (t * %du);" % (i, i + 3, i, 2 * i + 1))
    for i in range(NF): print("  float f%d = __uint_as_float((in[(t + %d) & 255u] & 0x007fffffu) | 0x3f000000u);" % (i, i))
    for i in range(NW): print("  u64 w%d = 0;" % i)
    for _ in range(n): print("  " + stmt())
    for i in range(NV): print("  out[t * NO + %d] = v%d;" % (i, i))
    for i in range(NF): print("  out[t * NO + %d] = __float_as_uint(f%d);" % (NV + i, i))
    print("}")
print("""static uint64_t hash_bytes(const void* p, size_t n) { const unsigned char* b = (const unsigned char*)p; uint64_t h = 1469598103934665603ull; for (size_t i = 0; i < n; ++i) { h ^= b[i]; h *= 1099511628211ull; } return h; }
int main() {
  const int n = 1024 + 77;
  std::vector<u32> a(256);
  uint64_t s = @SEED@;
  const u32 special[] = {0u, 1u, 0xffffffffu, 0x80000000u, 0x7fffffffu, 0x7f800000u, 0xff800000u, 0x7fc00000u, 0x00000001u, 0x3f800000u, 0xbf800000u, 31u, 32u};
  for (size_t i = 0; i < a.size(); ++i) { s = s * 6364136223846793005ull + 1442695040888963407ull; a[i] = (i % 3 == 0) ? special[(s >> 33) % 13] : (u32)(s >> 32); }
  u32 *din, *dout;
  CK(cudaMalloc(&din, 256 * 4)); CK(cudaMalloc(&dout, (size_t)n * NO * 4));
  CK(cudaMemcpy(din, a.data(), 256 * 4, cudaMemcpyHostToDevice));
  std::vector<u32> h((size_t)n * NO);
""".replace("@SEED@", str(seed)))
for k in range(nk):
    print("  for (int th : {128, 48, 33}) { CK(cudaMemset(dout, 0, (size_t)n * NO * 4)); k%d<<<(n + th - 1) / th, th>>>(din, dout, n); CK(cudaDeviceSynchronize()); CK(cudaMemcpy(h.data(), dout, h.size() * 4, cudaMemcpyDeviceToHost)); std::printf(\"k%d th=%%d %%016llx\\n\", th, (unsigned long long)hash_bytes(h.data(), h.size() * 4)); }" % (k, k))
print("  return 0;\n}")
