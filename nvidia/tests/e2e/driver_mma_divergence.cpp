int main() {
  unsigned vals[38];
  const unsigned short mods[6] = {211, 199, 163, 251, 223, 197};
  unsigned char out[6 * 32 * 4], ref[6 * 32 * 4];
  std::srand(7);
  for (int i = 0; i < 38; ++i) vals[i] = (unsigned)std::rand() ^ ((unsigned)std::rand() << 16);
  for (int p = 0; p < 6; ++p)
    for (int lane = 0; lane < 32; ++lane)
      for (int f = 0; f < 4; ++f) {
        // D[m][n] with n = 2 * (lane % 4) + (f & 1): every row of A is equal, and B[k][n] comes from lane 4n + (k % 16) / 4.
        const int n = 2 * (lane % 4) + (f & 1);
        int d = 0;
        for (int k = 0; k < 32; ++k)
          d += (signed char)(vals[32 + p] >> (8 * (k % 4))) * (signed char)(vals[4 * n + (k % 16) / 4] >> (8 * (k % 4)));
        const unsigned r = (unsigned)std::abs(d) % mods[p];
        ref[(p * 32 + lane) * 4 + f] = (unsigned char)((r != 0 && d < 0) ? mods[p] - r : r);
      }

  IS(cuInit(0), CUDA_SUCCESS);
  CUdevice dev;
  CUcontext ctx;
  IS(cuDeviceGet(&dev, 0), CUDA_SUCCESS);
  IS(cuDevicePrimaryCtxRetain(&ctx, dev), CUDA_SUCCESS);
  IS(cuCtxSetCurrent(ctx), CUDA_SUCCESS);
  CUmodule mod = nullptr;
  IS(cuModuleLoadData(&mod, kPtx), CUDA_SUCCESS);
  CUdeviceptr dv, dm, dout;
  IS(cuMemAlloc(&dv, sizeof vals), CUDA_SUCCESS);
  IS(cuMemAlloc(&dm, sizeof mods), CUDA_SUCCESS);
  IS(cuMemAlloc(&dout, sizeof out), CUDA_SUCCESS);
  IS(cuMemcpyHtoD(dv, vals, sizeof vals), CUDA_SUCCESS);
  IS(cuMemcpyHtoD(dm, mods, sizeof mods), CUDA_SUCCESS);
  if (failures) {
    std::printf("FAIL: setup\n");
    return 1;
  }
  for (const char* name : {"branch", "choose"}) {
    CUfunction fn = nullptr;
    unsigned zero = 0;
    void* args[7] = {&dv, &dm, &dout, &zero, &zero, &zero, &zero};   // the four trailing parameters are unused
    IS(cuModuleGetFunction(&fn, mod, name), CUDA_SUCCESS);
    if (!fn) continue;
    IS(cuLaunchKernel(fn, 1, 1, 1, 32, 1, 1, 0, nullptr, args, nullptr), CUDA_SUCCESS);
    IS(cuCtxSynchronize(), CUDA_SUCCESS);
    IS(cuMemcpyDtoH(out, dout, sizeof out), CUDA_SUCCESS);
    int bad = 0, first = -1;
    for (int i = 0; i < 6 * 32 * 4; ++i)
      if (out[i] != ref[i]) {
        ++bad;
        if (first < 0) first = i / 128;
      }
    std::printf("%s: %d of %d wrong, first in pass %d\n", name, bad, 6 * 32 * 4, first);
    check(bad == 0, name);
  }
  std::printf(failures ? "FAIL: %d checks\n" : "PASS: mma.sync after a divergent branch\n", failures);
  return failures ? 1 : 0;
}
