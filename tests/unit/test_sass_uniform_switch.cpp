//     __syncthreads();
//     if (valid[t]) {
//       float acc = 0;
//   #pragma unroll 1
//       for (int j = 0; j < n; ++j) acc += s[t * n + j];
//       out[t] = acc;
//     } else {
//       mask[t] = 0;
//     }
//   }
//
